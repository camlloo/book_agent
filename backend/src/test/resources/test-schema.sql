CREATE TABLE IF NOT EXISTS `user`(id BIGINT AUTO_INCREMENT PRIMARY KEY,username VARCHAR(32) UNIQUE,password VARCHAR(64),nickname VARCHAR(32),role VARCHAR(16),status INT,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS article(id BIGINT AUTO_INCREMENT PRIMARY KEY,title VARCHAR(128),summary VARCHAR(500),content MEDIUMTEXT,category_id BIGINT,status VARCHAR(16) DEFAULT 'DRAFT',view_count INT DEFAULT 0,published_at TIMESTAMP,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS category(id BIGINT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(64) UNIQUE,parent_id BIGINT,sort_order INT DEFAULT 0,FOREIGN KEY(parent_id) REFERENCES category(id));
CREATE TABLE IF NOT EXISTS tag(id BIGINT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(64) UNIQUE);
CREATE TABLE IF NOT EXISTS article_tag(article_id BIGINT,tag_id BIGINT,PRIMARY KEY(article_id,tag_id),FOREIGN KEY(article_id) REFERENCES article(id) ON DELETE CASCADE,FOREIGN KEY(tag_id) REFERENCES tag(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS task(id BIGINT AUTO_INCREMENT PRIMARY KEY,topic VARCHAR(128),stage VARCHAR(16),status VARCHAR(24),request_json MEDIUMTEXT,output MEDIUMTEXT,approved_content MEDIUMTEXT,article_id BIGINT,error VARCHAR(1000),run_id VARCHAR(36),started_at TIMESTAMP,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS task_checkpoint(id BIGINT AUTO_INCREMENT PRIMARY KEY,task_id BIGINT,stage VARCHAR(16),run_id VARCHAR(36),generated_content MEDIUMTEXT,approved_content MEDIUMTEXT,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,UNIQUE(task_id,run_id),FOREIGN KEY(task_id) REFERENCES task(id));
CREATE TABLE IF NOT EXISTS book (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(128) NOT NULL,
 summary VARCHAR(500) NULL,
 content MEDIUMTEXT NOT NULL,
 revision BIGINT NOT NULL DEFAULT 1,
 indexed_revision BIGINT NOT NULL DEFAULT 0,
 index_status VARCHAR(16) NOT NULL DEFAULT 'QUEUED',
 index_error VARCHAR(1000) NULL,
 chunk_count INT NOT NULL DEFAULT 0,
 deleted TINYINT NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS book_file (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 book_id BIGINT NOT NULL,
 original_name VARCHAR(255) NOT NULL,
 extension VARCHAR(8) NOT NULL,
 object_key VARCHAR(255) NOT NULL UNIQUE,
 file_size BIGINT NOT NULL,
 sha256 VARCHAR(64) NOT NULL,
 deleted TINYINT NOT NULL DEFAULT 0,
 purged TINYINT NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_file_book FOREIGN KEY(book_id) REFERENCES book(id)
);
CREATE TABLE IF NOT EXISTS book_index_job (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 book_id BIGINT NOT NULL,
 revision BIGINT NOT NULL,
 operation VARCHAR(16) NOT NULL DEFAULT 'INDEX',
 status VARCHAR(16) NOT NULL DEFAULT 'QUEUED',
 run_id VARCHAR(36) NULL,
 error VARCHAR(1000) NULL,
 started_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_index_book FOREIGN KEY(book_id) REFERENCES book(id)
);
CREATE TABLE IF NOT EXISTS task_book (
 task_id BIGINT NOT NULL PRIMARY KEY,
 knowledge_book_id BIGINT NOT NULL,
 result_book_id BIGINT NULL,
 CONSTRAINT fk_task_book_task FOREIGN KEY(task_id) REFERENCES task(id) ON DELETE CASCADE,
 CONSTRAINT fk_task_book_source FOREIGN KEY(knowledge_book_id) REFERENCES book(id),
 CONSTRAINT fk_task_book_result FOREIGN KEY(result_book_id) REFERENCES book(id)
);
CREATE TABLE IF NOT EXISTS book_source (
 book_id BIGINT NOT NULL PRIMARY KEY,
 mode VARCHAR(16) NOT NULL,
 FOREIGN KEY(book_id) REFERENCES book(id)
);
CREATE TABLE IF NOT EXISTS book_publication(book_id BIGINT PRIMARY KEY,status VARCHAR(16) DEFAULT 'DRAFT',category_id BIGINT,view_count INT DEFAULT 0,published_at TIMESTAMP,FOREIGN KEY(book_id) REFERENCES book(id),FOREIGN KEY(category_id) REFERENCES category(id) ON DELETE SET NULL);
CREATE TABLE IF NOT EXISTS book_tag(book_id BIGINT,tag_id BIGINT,PRIMARY KEY(book_id,tag_id),FOREIGN KEY(book_id) REFERENCES book(id),FOREIGN KEY(tag_id) REFERENCES tag(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS legacy_article_book(article_id BIGINT PRIMARY KEY,book_id BIGINT UNIQUE,FOREIGN KEY(book_id) REFERENCES book(id));
CREATE TABLE IF NOT EXISTS task_book_result(task_id BIGINT PRIMARY KEY,result_book_id BIGINT,FOREIGN KEY(task_id) REFERENCES task(id) ON DELETE CASCADE,FOREIGN KEY(result_book_id) REFERENCES book(id));

